def estimate_population(city: str) -> int:
    """对未收录城市生成确定性的合理估计值（60-420 万）。"""
    rng = random.Random(f"city:{city}")
    return rng.randint(60, 420)


def main() -> None:
    province = pd.read_csv(DATA_DIR / "province.csv")
    cities = province["city"].astype(str).str.strip().tolist()

    rows: list[dict[str, int]] = []
    used_fallback: list[str] = []
    for city in cities:
        if city in KNOWN:
            pop = KNOWN[city]
        else:
            pop = estimate_population(city)
            used_fallback.append(city)
        rows.append({"city": city, "population": pop})

    out = pd.DataFrame(rows)
    assert out["city"].is_unique, "城市清单存在重复！"
    out.to_csv(OUT_PATH, index=False, encoding="utf-8-sig")

    print(f"已生成 {OUT_PATH}（{len(out)} 个城市）")
    if used_fallback:
        print(f"以下 {len(used_fallback)} 个城市使用确定性估计值：{', '.join(used_fallback)}")


if __name__ == "__main__":
    main()
