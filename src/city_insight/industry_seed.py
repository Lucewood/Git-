REGION_OF_PROVINCE: dict[str, str] = {
    province: region
    for region, provinces in REGION_PROVINCES.items()
    for province in provinces
}

# ---------------------------------------------------------------------------
# 生成参数
# ---------------------------------------------------------------------------
REF_INCOME = 95000.0                  # 参考城市年收入（元），用于产业薪资缩放
SALARY_SCALE_BOUNDS = (0.55, 2.2)     # 薪资缩放系数上下限，避免极端城市失真
SKILLS_PER_INDUSTRY = 4               # 每个产业抽取的核心技能数
CATEGORY_COUNT_RANGE = (3, 4)         # 未收录城市抽取的支柱产业数量区间
SHARE_TOTAL_RANGE = (42.0, 62.0)      # 支柱产业合计就业占比区间（%）


def salary_scale(income: float | None) -> float:
    """城市年收入 → 产业薪资缩放系数（缺失或非法时返回 1.0）。"""
    try:
        value = float(income)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return 1.0
    if not math.isfinite(value) or value <= 0:
        return 1.0
    low, high = SALARY_SCALE_BOUNDS
    return min(max(value / REF_INCOME, low), high)


def categories_for(city: str, province: str) -> tuple[str, ...]:
    """返回城市的支柱产业大类：优先取人工收录口径，否则从省份产业池确定性抽取。"""
    known = CITY_LEADING_INDUSTRIES.get(city)
    if known:
        return known
    pool = PROVINCE_INDUSTRY_POOL.get(province, DEFAULT_INDUSTRY_POOL)
    rng = random.Random(f"category:{city}")
    lo, hi = CATEGORY_COUNT_RANGE
    k = min(rng.randint(lo, hi), len(pool))
    return tuple(pool[idx] for idx in sorted(rng.sample(range(len(pool)), k)))


def _pick_skills(
    pool: tuple[str, ...], rng: random.Random, k: int = SKILLS_PER_INDUSTRY
) -> tuple[str, ...]:
    """从技能池中确定性地抽取 k 项（按池内原顺序返回，便于展示与比对）。"""
    k = min(k, len(pool))
    picks = sorted(rng.sample(range(len(pool)), k))
    return tuple(pool[idx] for idx in picks)


def seed_records(cities: pd.DataFrame) -> list[dict[str, object]]:
    """按城市生成支柱产业明细记录（确定性、可复现）。

    Args:
        cities: 需包含 city / province / income 列的 DataFrame。

    Returns:
        记录列表，字段与 config.INDUSTRY_COLS 一致；同一城市的多条记录按
        产业大类顺序排列，就业占比合计落在 SHARE_TOTAL_RANGE 区间内。
    """
    records: list[dict[str, object]] = []
    for row in cities.itertuples(index=False):
        city = str(row.city)
        province = str(getattr(row, "province", ""))
        scale = salary_scale(getattr(row, "income", None))
        rng = random.Random(f"industry:{city}")

        categories = categories_for(city, province)
        weights = [rng.uniform(0.6, 1.4) for _ in categories]
        weight_sum = sum(weights) or 1.0
        total_share = rng.uniform(*SHARE_TOTAL_RANGE)

        for category, weight in zip(categories, weights):
            meta = CATEGORY_META[category]
            salary = meta.base_salary * scale * rng.uniform(0.90, 1.10)
            records.append(
                {
                    "city": city,
                    "industry": meta.industries[rng.randrange(len(meta.industries))],
                    "category": category,
                    "share_pct": round(total_share * weight / weight_sum, 1),
                    "avg_salary": int(round(salary / 100.0) * 100),
                    "demand_index": round(rng.uniform(*meta.demand_range), 1),
                    "growth_pct": round(rng.uniform(*meta.growth_range), 1),
                    "education": meta.education,
                    "skills": "|".join(_pick_skills(meta.skills, rng)),
                }
            )
    return records


def records_by_region(
    records: Iterable[dict[str, object]], province_map: dict[str, str]
) -> dict[str, list[dict[str, object]]]:
    """把记录按省份所属区域分桶（用于生成区域分页的快照页面）。"""
    buckets: dict[str, list[dict[str, object]]] = {
        region: [] for region in REGION_PROVINCES
    }
    for record in records:
        province = province_map.get(str(record.get("city", "")), "")
        region = REGION_OF_PROVINCE.get(province)
        if region is None:  # 兜底：未知省份统一放入「其他」
            buckets.setdefault("其他", []).append(record)
        else:
            buckets[region].append(record)
    return buckets
